#!/usr/bin/env node
// Writes config.js from the kit's CombatConfig.luau (evaluated by the real luau CLI), so the lab
// always runs with the numbers you'd ship. Re-run after editing CombatConfig.luau.
'use strict';
const fs = require('fs');
const path = require('path');
const L = require(path.join(__dirname, '..', '..', '..', 'skills', 'roblox-combat', 'tests', 'run-luau.cjs'));
if (!L.luauAvailable()) { console.error('needs the luau CLI (brew install luau)'); process.exit(1); }
const cfg = L.config();
const text = `// GENERATED by build-config.cjs from skills/roblox-combat/assets/kit/shared/Combat/CombatConfig.luau\n(function (root) { const CONFIG = ${JSON.stringify(cfg, null, 1)};\nif (typeof module === 'object' && module.exports) module.exports = CONFIG; else root.COMBAT_CONFIG = CONFIG; })(typeof self !== 'undefined' ? self : this);\n`;
fs.writeFileSync(path.join(__dirname, 'config.js'), text);
console.log('wrote config.js');
