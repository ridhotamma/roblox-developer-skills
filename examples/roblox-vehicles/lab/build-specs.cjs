#!/usr/bin/env node
// Bundles the skill's spec JSONs and the numbers rveh.cjs reports for them into specs.js, so
// the lab (Node and browser) can compare what the simulated kit does against the report.
'use strict';
const fs = require('fs');
const path = require('path');
const skill = path.join(__dirname, '..', '..', '..', 'skills', 'roblox-vehicles');
const R = require(path.join(skill, 'scripts', 'rveh.cjs'));
const dir = path.join(skill, 'specs');
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const raw = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  const r = R.report(R.normalize(raw));
  out[raw.name] = {
    raw,
    report: {
      t60kmh: r.launch.t60kmh, t100: r.launch.t100, quarter: r.launch.quarter, topKmh: r.top.kmh, topLimiter: r.top.limiter,
      brakeM: r.brake.meters, lateralG: r.lateralG, hp: r.peakHp, sagFront: r.susp.front.sagStuds, sagRear: r.susp.rear.sagStuds,
    },
  };
}
const text = `// GENERATED by build-specs.cjs from skills/roblox-vehicles/specs + rveh.cjs report\n(function (root) { const SPECS = ${JSON.stringify(out, null, 1)};\nif (typeof module === 'object' && module.exports) module.exports = SPECS; else root.VEHICLE_SPECS = SPECS; })(typeof self !== 'undefined' ? self : this);\n`;
fs.writeFileSync(path.join(__dirname, 'specs.js'), text);
console.log(`wrote specs.js (${Object.keys(out).join(', ')})`);
