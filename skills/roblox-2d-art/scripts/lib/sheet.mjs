// Sprite sheets (ImageLabel ImageRectOffset / ImageRectSize) and ParticleEmitter flipbooks (Grid2x2 / 4x4 / 8x8).
import * as R from './raster.mjs';

// frames: [{ name, img: { w, h, rgba } }]. o: { cols, pad (px, edge pixels extruded into it), cell: [w, h], flipbook: 2|4|8,
// size (flipbook sheet side, default 1024 or smaller), margin (flipbook spacing as a fraction of a cell), fps, name }
export function pack(frames, o = {}) {
  if (!frames.length) throw new Error('no frames to pack');
  if (o.flipbook) return flipbook(frames, o);
  const pad = o.pad ?? 2, cw = o.cell?.[0] ?? Math.max(...frames.map(f => f.img.w)), ch = o.cell?.[1] ?? Math.max(...frames.map(f => f.img.h));
  const cols = o.cols || Math.ceil(Math.sqrt(frames.length * ch / cw)), rows = Math.ceil(frames.length / cols), CW = cw + pad * 2, CH = ch + pad * 2;
  const W = cols * CW, H = rows * CH, rgba = new Uint8Array(W * H * 4), rects = [];
  frames.forEach((f, i) => {
    let img = f.img; if (img.w > cw || img.h > ch) { const s = Math.min(cw / img.w, ch / img.h); img = R.toRGBA8(R.resize(R.fromRGBA8(img), Math.max(1, Math.round(img.w * s)), Math.max(1, Math.round(img.h * s)))); }
    const x0 = (i % cols) * CW + pad + Math.floor((cw - img.w) / 2), y0 = Math.floor(i / cols) * CH + pad + Math.floor((ch - img.h) / 2);
    for (let y = -pad; y < img.h + pad; y++) for (let x = -pad; x < img.w + pad; x++) {   // extrude edges into the padding: no bleeding between frames when filtered
      const sx = Math.min(img.w - 1, Math.max(0, x)), sy = Math.min(img.h - 1, Math.max(0, y)), s = (sy * img.w + sx) * 4, d = ((y0 + y) * W + x0 + x) * 4;
      for (let c = 0; c < 4; c++) rgba[d + c] = img.rgba[s + c];
    }
    rects.push({ name: f.name, x: x0, y: y0, w: img.w, h: img.h });
  });
  return { img: R.bleed({ w: W, h: H, rgba }), rects, cols, rows, luau: luauGrid(o.name || 'Sheet', W, H, rects, o.fps || 12) };
}

function flipbook(frames, o) {
  const n = +o.flipbook, need = n * n; if (![2, 4, 8].includes(n)) throw new Error('flipbook must be 2, 4 or 8 (Grid2x2 / Grid4x4 / Grid8x8)');
  if (frames.length > need) throw new Error(`${frames.length} frames do not fit a ${n}x${n} flipbook (max ${need})`);
  const S = o.size || Math.min(1024, n * Math.max(...frames.map(f => Math.max(f.img.w, f.img.h)))), cell = Math.floor(S / n), inner = Math.floor(cell * (1 - 2 * (o.margin ?? 0.04)));
  const rgba = new Uint8Array(S * S * 4), rects = [];
  frames.forEach((f, i) => {
    const s = inner / Math.max(f.img.w, f.img.h), w = Math.max(1, Math.round(f.img.w * s)), h = Math.max(1, Math.round(f.img.h * s)), img = R.toRGBA8(R.resize(R.fromRGBA8(f.img), w, h));
    const x0 = (i % n) * cell + Math.floor((cell - w) / 2), y0 = Math.floor(i / n) * cell + Math.floor((cell - h) / 2);
    for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) { const sI = (y * w + x) * 4, d = ((y0 + y) * S + x0 + x) * 4; for (let c = 0; c < 4; c++) rgba[d + c] = img.rgba[sI + c]; }
    rects.push({ name: f.name, x: (i % n) * cell, y: Math.floor(i / n) * cell, w: cell, h: cell });
  });
  const fps = Math.min(30, o.fps || 24);
  const luau = `-- ${o.name || 'Flipbook'}: ${S}x${S} ParticleEmitter flipbook, ${frames.length} frames in a ${n}x${n} grid\n` +
    `-- Upload the PNG, then set these on the ParticleEmitter (FlipbookFramerate max is 30).\n` +
    `emitter.Texture = "rbxassetid://0" -- replace with the uploaded image id\nemitter.FlipbookLayout = Enum.ParticleFlipbookLayout.Grid${n}x${n}\n` +
    `emitter.FlipbookMode = Enum.ParticleFlipbookMode.${o.mode || 'Loop'} -- Loop | OneShot | PingPong | Random\nemitter.FlipbookFramerate = NumberRange.new(${fps})\n` +
    (frames.length < need ? `-- note: only ${frames.length} of ${need} cells are filled; empty cells show as blank frames (use OneShot timing or fill them)\n` : '');
  return { img: R.bleed({ w: S, h: S, rgba }), rects, cols: n, rows: n, luau };
}

function luauGrid(name, W, H, rects, fps) {
  const id = name.replace(/[^A-Za-z0-9_]/g, '_');
  return `-- ${name}: ${W}x${H} sprite sheet, ${rects.length} frames. Generated by roblox-2d-art.
-- Upload the PNG, put its id in Sheet.image, then Sheet.apply(imageLabel, "frameName" or index) or Sheet.play(imageLabel).
local RunService = game:GetService("RunService")

local ${id} = {
\timage = "rbxassetid://0", -- replace with the uploaded image id
\tsize = Vector2.new(${W}, ${H}),
\tfps = ${fps},
\tframes = {
${rects.map(r => `\t\t["${r.name}"] = { offset = Vector2.new(${r.x}, ${r.y}), size = Vector2.new(${r.w}, ${r.h}) },`).join('\n')}
\t},
\torder = { ${rects.map(r => `"${r.name}"`).join(', ')} },
}

function ${id}.apply(label: ImageLabel | ImageButton, frame: string | number)
\tlocal f = if type(frame) == "number" then ${id}.frames[${id}.order[frame]] else ${id}.frames[frame]
\tlabel.Image = ${id}.image
\tlabel.ImageRectOffset = f.offset
\tlabel.ImageRectSize = f.size
end

-- Loops through \`order\` until the returned stop() is called (or the label is destroyed).
function ${id}.play(label: ImageLabel | ImageButton, fps: number?)
\tlocal t, i, step = 0, 1, 1 / (fps or ${id}.fps)
\t${id}.apply(label, 1)
\tlocal conn
\tconn = RunService.Heartbeat:Connect(function(dt)
\t\tif not label.Parent then conn:Disconnect() return end
\t\tt += dt
\t\twhile t >= step do
\t\t\tt -= step
\t\t\ti = i % #${id}.order + 1
\t\t\t${id}.apply(label, i)
\t\tend
\tend)
\treturn function() conn:Disconnect() end
end

return ${id}
`;
}
