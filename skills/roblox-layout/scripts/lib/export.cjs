// Turns a loaded layout into things Studio can use: a .rbxmx model to drag in, a command-bar
// script, a ModuleScript for LayoutBuilder at runtime, and the data blob for the HTML preview.
"use strict";
const fs = require("fs");
const path = require("path");
const G = require("./geom.cjs");

const n = v => { const r = Math.round(v * 1000) / 1000; return Object.is(r, -0) ? "0" : String(r); };

// Group identical geometry so each distinct object is described once.
function meshes(L) {
  const keys = new Map(), list = [], names = [], count = new Map();
  const of = it => {
    const sig = JSON.stringify(it.parts);
    if (!keys.has(sig)) { const c = (count.get(it.kind) || 0) + 1; count.set(it.kind, c); keys.set(sig, list.length); list.push(it.parts); names.push(c === 1 ? it.kind : `${it.kind}#${c}`); }
    return keys.get(sig);
  };
  const idx = L.items.map(of);
  return { list, names, idx };
}

function previewData(L, report) {
  const m = meshes(L), lay = L.layout;
  return {
    name: lay.name || "Layout", type: lay.type || "custom", bounds: L.bounds.map(v => G.round(v, 10)), spawn: lay.spawn, focus: lay.focus,
    zones: lay.zones || [], paths: lay.paths || [], pois: lay.pois || [],
    meshes: m.list.map(parts => parts.map(p => ({ s: p.s, p: p.p.map(v => G.round(v)), z: p.z.map(v => G.round(v)), c: p.c, m: p.m, r: p.r || undefined }))),
    items: L.items.map((it, i) => ({ i: it.id, k: it.kind, m: m.idx[i], p: [G.round(it.x), G.round(it.y), G.round(it.z)], r: it.rot, f: [G.round(it.fw), G.round(it.fd)], s: [G.round(it.w), G.round(it.h), G.round(it.d)], o: it.role, w: it.walkable ? 1 : 0,
      cl: Object.keys(it.clear).length ? it.clear : undefined, c: it.color, sh: it.parts[0] && it.parts[0].s !== "block" && it.parts.length < 4 ? it.parts[0].s : undefined, l: it.label })),
    report,
  };
}
function previewHtml(L, report) {
  const tpl = fs.readFileSync(path.join(__dirname, "..", "..", "assets", "viewer.html"), "utf8");
  const json = JSON.stringify(previewData(L, report)).replace(/</g, "\\u003c");
  return tpl.replace("/*__DATA__*/null", () => json).replace("<title>Layout Preview</title>", `<title>${(L.layout.name || "Layout").replace(/[<&]/g, "")} Layout</title>`);
}

// ---- Luau ----
function luau(v, ind = "") {
  if (v === null || v === undefined) return "nil";
  if (typeof v === "number") return n(v);
  if (typeof v === "boolean") return String(v);
  if (typeof v === "string") return JSON.stringify(v);
  if (Array.isArray(v)) { const flat = v.every(x => typeof x !== "object" || x === null); return flat ? `{ ${v.map(x => luau(x)).join(", ")} }` : `{\n${v.map(x => ind + "\t" + luau(x, ind + "\t")).join(",\n")},\n${ind}}`; }
  const ks = Object.keys(v).filter(k => v[k] !== undefined);
  return `{\n${ks.map(k => `${ind}\t${/^[A-Za-z_]\w*$/.test(k) ? k : `[${JSON.stringify(k)}]`} = ${luau(v[k], ind + "\t")}`).join(",\n")},\n${ind}}`;
}
function moduleData(L) {
  const m = meshes(L), lay = L.layout, kinds = {};
  m.list.forEach((parts, i) => { kinds[m.names[i]] = parts.map(p => [p.s, ...p.p.map(v => G.round(v)), ...p.z.map(v => G.round(v)), p.c.slice(1), p.m, p.r || 0]); });
  return {
    name: lay.name || "Layout", type: lay.type || "custom", seed: lay.seed, spawn: lay.spawn, bakedScale: true,
    kinds,
    items: L.items.map((it, i) => [m.names[m.idx[i]], it.id, G.round(it.x), G.round(it.y), G.round(it.z), it.rot, it.role, it.kind, it.scale, it.zone || false, it.label || false, it.tags.length ? it.tags : false]),
    paths: (lay.paths || []).map(p => ({ id: p.id, kind: p.kind, width: p.width, y: p.y, points: p.points })),
    zones: (lay.zones || []).map(z => ({ id: z.id, label: z.label, kind: z.kind, rect: z.rect, circle: z.circle, y: z.y })),
    route: lay.route,
  };
}
const head = L => `-- ${L.layout.name || "Layout"} (${L.layout.type || "custom"}): ${L.items.length} objects. Generated by roblox-layout; edit the layout spec and re-export instead of editing this file.\n`;
function toModule(L) { return `--!nocheck\n${head(L)}return ${luau(moduleData(L))}\n`; }
function toScript(L) {
  const builder = fs.readFileSync(path.join(__dirname, "..", "..", "assets", "kit", "shared", "Layout", "LayoutBuilder.luau"), "utf8").replace(/^--!strict\n/, "");
  return `${head(L)}-- Paste into Studio's command bar (View > Command Bar), or run as a plugin script. Ctrl+Z undoes it.
local ChangeHistoryService = game:GetService("ChangeHistoryService")
local LayoutBuilder = (function()
${builder}end)()
local layout = ${luau(moduleData(L))}
local recording = ChangeHistoryService:TryBeginRecording("Build layout")
local model = LayoutBuilder.Build(layout, { Parent = workspace })
game:GetService("Selection"):Set({ model })
if recording then ChangeHistoryService:FinishRecording(recording, Enum.FinishRecordingOperation.Commit) end
print(("Built %s: %d objects"):format(model.Name, #layout.items))
`;
}

// ---- rbxmx ----
const MATERIAL = { Plastic: 256, SmoothPlastic: 272, Neon: 288, Wood: 512, WoodPlanks: 528, Marble: 784, Slate: 800, Concrete: 816, Granite: 832, Pebble: 864, Cobblestone: 880, Rock: 896, Sandstone: 912, Brick: 1024, CorrodedMetal: 1040, DiamondPlate: 1056, Foil: 1072, Metal: 1088, Grass: 1280, Sand: 1296, Fabric: 1312, Snow: 1328, Mud: 1344, Ground: 1360, Asphalt: 1376, Ice: 1536, Glass: 1568, LeafyGrass: 1408, Pavement: 836 };
const FOLDER = { floor: "Structure", wall: "Structure", window: "Structure", lintel: "Structure", ceiling: "Structure", furniture: "Furniture", prop: "Props", decor: "Props", light: "Props", nature: "Nature", building: "Buildings", platform: "Gameplay", hazard: "Gameplay", marker: "Gameplay", structure: "Gameplay" };
const xml = s => String(s).replace(/[<>&"]/g, c => ({ "<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;" }[c]));
function toRbxmx(L) {
  let ref = 0; const R = () => `RBX${++ref}`;
  const cframe = (p, m) => `<CoordinateFrame name="CFrame"><X>${n(p[0])}</X><Y>${n(p[1])}</Y><Z>${n(p[2])}</Z>${["R00", "R01", "R02", "R10", "R11", "R12", "R20", "R21", "R22"].map((k, i) => `<${k}>${n(m[i])}</${k}>`).join("")}</CoordinateFrame>`;
  const part = (it, p) => {
    const [wx, wz] = G.l2w(it.x, it.z, it.rot, p.p[0], p.p[2]), pos = [wx, it.y + p.p[1], wz], yaw = G.rad(it.rot + (p.r || 0)), c = Math.cos(yaw), s = Math.sin(yaw);
    const cyl = p.s === "cylinder", m = cyl ? [0, -c, s, 1, 0, 0, 0, s, c] : [c, 0, s, 0, 1, 0, -s, 0, c], size = cyl ? [p.z[1], p.z[0], p.z[2]] : p.z;
    const col = (0xFF000000 + parseInt(p.c.slice(1), 16)) >>> 0, cls = p.s === "wedge" ? "WedgePart" : "Part", noCollide = it.role === "decor" || it.role === "light";
    return `<Item class="${cls}" referent="${R()}"><Properties><string name="Name">${cls === "WedgePart" ? "Wedge" : "Part"}</string><bool name="Anchored">true</bool>${noCollide ? '<bool name="CanCollide">false</bool>' : ""}${cframe(pos, m)}<Vector3 name="size"><X>${n(size[0])}</X><Y>${n(size[1])}</Y><Z>${n(size[2])}</Z></Vector3><Color3uint8 name="Color3uint8">${col}</Color3uint8><token name="Material">${MATERIAL[p.m] || 272}</token>${cls === "Part" ? `<token name="shape">${p.s === "ball" ? 0 : cyl ? 2 : 1}</token>` : ""}<float name="Transparency">${p.m === "Glass" ? 0.5 : 0}</float><token name="TopSurface">0</token><token name="BottomSurface">0</token></Properties></Item>`;
  };
  const folders = new Map();
  for (const it of L.items) {
    const f = FOLDER[it.role] || "Props"; if (!folders.has(f)) folders.set(f, []);
    const attrs = ""; void attrs;
    folders.get(f).push(`<Item class="Model" referent="${R()}"><Properties><string name="Name">${xml(it.id)}</string></Properties>${it.parts.map(p => part(it, p)).join("")}</Item>`);
  }
  // trails and paths as flat strips
  const strips = [];
  for (const pa of L.layout.paths || []) for (let i = 1; i < pa.points.length; i++) {
    const a = pa.points[i - 1], b = pa.points[i], len = Math.hypot(b[0] - a[0], b[1] - a[1]), rot = Math.atan2(-(b[0] - a[0]), -(b[1] - a[1])) * 180 / Math.PI, color = pa.kind === "trail" ? "#B89466" : "#D9CDB4", mat = pa.kind === "trail" ? "Ground" : "Cobblestone";
    const it = { x: (a[0] + b[0]) / 2, y: pa.y || 0.05, z: (a[1] + b[1]) / 2, rot, role: "decor" };
    strips.push(part(it, { s: "block", p: [0, 0, 0], z: [pa.width, 0.2, len], c: color, m: mat }), part({ x: b[0], y: pa.y || 0.05, z: b[1], rot: 0, role: "decor" }, { s: "cylinder", p: [0, 0, 0], z: [pa.width, 0.2, pa.width], c: color, m: mat }));
  }
  if (strips.length) folders.set("Paths", strips);
  const body = [...folders].map(([name, kids]) => `<Item class="Folder" referent="${R()}"><Properties><string name="Name">${name}</string></Properties>${kids.join("")}</Item>`).join("\n");
  return `<roblox xmlns:xmime="http://www.w3.org/2005/05/xmlmime" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xsi:noNamespaceSchemaLocation="http://www.roblox.com/roblox.xsd" version="4">\n<Item class="Model" referent="${R()}"><Properties><string name="Name">${xml(L.layout.name || "Layout")}</string></Properties>\n${body}\n</Item>\n</roblox>\n`;
}

// Catalog as a Luau module for the runtime generators (default palette baked in).
function catalogModule(C) {
  const pal = C.palette("rustic"), kinds = {}, info = {};
  for (const name of Object.keys(C.K)) {
    const it = C.resolve({ kind: name }, C.K, pal, 0);
    kinds[name] = it.parts.map(p => [p.s, ...p.p.map(v => G.round(v)), ...p.z.map(v => G.round(v)), p.c.slice(1), p.m, p.r || 0]);
    info[name] = { size: [it.w, it.h, it.d], foot: [it.fw, it.fd], role: it.role, walkable: it.walkable || undefined, clear: Object.keys(it.clear).length ? it.clear : undefined, space: it.space };
  }
  const sets = {};
  for (const [name, fn] of Object.entries(C.SETS)) sets[name] = fn({}).map(e => ({ kind: e.kind, lx: e.lx || 0, lz: e.lz || 0, rot: e.rot || 0, size: e.size, scale: e.scale }));
  const colors = {}; for (const [k, v] of Object.entries(pal)) colors[k] = v.slice(1);
  return `--!nocheck\n-- Generated by \`node scripts/rlayout.cjs build-kit\` from scripts/lib/catalog.cjs. Do not edit by hand.\n-- kinds: blockout parts per kind { shape, x, y, z, sizeX, sizeY, sizeZ, colour, material, yaw }.\n-- info: size, footprint, role and the free space each kind needs. sets: ready-made groups. colors: named colours.\nreturn {\n\tkinds = ${luau(kinds, "\t")},\n\tinfo = ${luau(info, "\t")},\n\tsets = ${luau(sets, "\t")},\n\tcolors = ${luau(colors, "\t")},\n}\n`;
}

module.exports = { previewData, previewHtml, toModule, toScript, toRbxmx, catalogModule, moduleData, luau, MATERIAL };
